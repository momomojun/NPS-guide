export type CreatorPlatform = "youtube" | "bilibili";

/** 视频用的语言 */
export type CreatorLanguage = "zh" | "en" | "ja" | "ko" | "es" | "fr" | "it" | "de";

/** 整理依据：文稿（字幕）和博主写的图文最可靠，其次是简介里写的行程、视频章节，只有标题和标签的最粗 */
export type CreatorBasis = "transcript" | "article" | "description" | "chapters" | "metadata";

/** 视频，还是博主写的图文（B 站专栏、图文动态） */
export type CreatorFormat = "video" | "article";

export interface CreatorDay {
  label: string;
  /** 景点 id 或地名 */
  stops: string[];
}

export interface CreatorRoute {
  /** "yt-视频 id"、"bili-BV 号"；图文是 "bili-cv 号"（专栏）或 "bili-opus-动态 id" */
  id: string;
  platform: CreatorPlatform;
  /** 不写就是视频 */
  format?: CreatorFormat;
  language: CreatorLanguage;
  /** 博主来自哪里（简介或视频里说了才写） */
  origin?: string;
  url: string;
  title: string;
  creator: string;
  /** 发布年月 */
  published: string;
  /** 播放量；图文是阅读量 */
  views: number;
  /** 视频多长；图文没有 */
  durationMin?: number;
  parks: string[];
  /** 玩了几天（视频里说了才有） */
  days?: number;
  /** 什么时候去的（视频里说了才有） */
  visited?: string;
  basis: CreatorBasis;
  /** 一两句概括：怎么玩、适合谁、博主的总体评价 */
  summary: string;
  route?: CreatorDay[];
  /** route 是不是按天排的：是的话可以照着排进行程的每一天；不是（比如“半天玩法”“任选徒步”）就只把景点加进行程 */
  byDay?: boolean;
  /** 博主对具体景点的看法（转述） */
  notes?: { stop: string; text: string }[];
  tips?: string[];
}

