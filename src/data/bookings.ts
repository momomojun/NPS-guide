// 每条写明相对于去的那天，从哪天开始能订或申请；行程页按行程日期算出“什么时候去订”。
// 规则来自官方页面，查的日期写在 verified 里。每年都可能变，出发前以 url 的页面为准。

export type BookingKind =
  | "lodging"
  | "campground"
  | "permit"
  | "lottery"
  | "timed-entry"
  | "tour"
  | "shuttle"
  | "transport";

/** "MM-DD"，每年一样 */
export type MonthDay = string;

export type BookingWindow =
  /** 去的那天往前推 months 个月或 days 天开放（Recreation.gov 营地 6 个月滚动） */
  | { type: "rolling"; months?: number; days?: number; time?: string; tz?: string }
  /**
   * 按月整块放：去的日子在每月 visitDay 号（不写就是 day 号）及以后的，在 monthsAhead 个月前的 day 号开放
   * （优胜美地营地 15 号放 5 个月后的一整段；落基山分时段入园 1 号放下个月；黄石园内酒店 5 号放明年同一整个月）
   */
  | { type: "block"; day: number; visitDay?: number; monthsAhead: number; time?: string; tz?: string }
  /** 按季节抽签：去的日子在 visit 里，就在 apply 这段时间申请（可能在前一年），results 出结果 */
  | {
      type: "seasonal-lottery";
      seasons: { visit: [MonthDay, MonthDay]; apply: [MonthDay, MonthDay]; results?: MonthDay }[];
      time?: string;
      tz?: string;
    }
  /** 按季度放票：去的日子在 visit 里，就在这一季开始前最近的 opens 那天放（锡安窄缝许可每季前一个月的 5 号） */
  | { type: "seasonal-release"; seasons: { visit: [MonthDay, MonthDay]; opens: MonthDay }[]; time?: string; tz?: string }
  /**
   * 按月抽签：去的月份往前数 monthsAhead 个月，那个月的 applyDays（默认整个月）申请，
   * 下个月的 resultsDay 号出结果（The Wave 提前 4 个月、幻影牧场提前 14 个月）
   */
  | { type: "monthly-lottery"; monthsAhead: number; applyDays?: [number, number]; resultsDay?: number }
  /** 提前几天开放或抽签（天使降临前一天抽签、半穹顶前两天抽签），until 是当天几点截止，results 是当天几点出结果 */
  | { type: "days-before"; days: number; time?: string; tz?: string; until?: string; results?: string }
  /** 某一年固定一天开放（比如公布了 2027 年的开订日期） */
  | { type: "fixed-date"; opens: string; time?: string; tz?: string; forYear?: number }
  /** 没有固定的开放日（比如整季的团都已经在卖），越早订越好 */
  | { type: "anytime" }
  /** 不能预约，先到先得 */
  | { type: "first-come" };

export interface BookingRule {
  id: string;
  park: string;
  /** 针对的景点或住宿 id；空数组、也没有 places 的，是整个公园都要（比如分时段入园） */
  targets: string[];
  /** 针对的是我们没收录的地方（营地、别的步道）：只在公园页列出，不进行程 */
  places?: string[];
  kind: BookingKind;
  titleZh: string;
  /** 去的日子在这些日期内才要订（"MM-DD"，可以跨年）；不写就是全年 */
  applies?: { from: MonthDay; to: MonthDay }[];
  window: BookingWindow;
  /** 错过了还有的机会（比如季度抽签错过了，还有前一天抽签） */
  also?: BookingWindow[];
  url: string;
  noteZh: string;
  source: string;
  verified: string;
}

